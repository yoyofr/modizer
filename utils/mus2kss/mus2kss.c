#define FST2_BIN_SIZE 2297
#define MUS_DATA_SIZE 0x4000
#define KSS_HEADER_SIZE 0x10

typedef enum {
    MUS2KSS_MODE_FMPAC = 0,
    MUS2KSS_MODE_MSXAUDIO = 1
} mus2kss_mode_t;

/*
 * Convert a MUS file to KSS format in memory (without drumkit)
 */
static int mus2kss_convert_simple(const uint8_t *mus_data, size_t mus_size,
                                   uint8_t *kss_data, size_t *kss_size,
                                   mus2kss_mode_t mode)
{
    uint8_t chip_value, kss_value;
    size_t offset = 0;
    size_t mus_copy_size;
    uint8_t fst2_patched[FST2_BIN_SIZE];

    /* Set chip-specific values */
    if (mode == MUS2KSS_MODE_FMPAC) {
        chip_value = 0x01;
        kss_value = 0x01;
    } else {
        chip_value = 0x00;
        kss_value = 0x08;
    }

    /* Build KSS header (16 bytes) */
    kss_data[offset++] = 'K';
    kss_data[offset++] = 'S';
    kss_data[offset++] = 'C';
    kss_data[offset++] = 'C';
    kss_data[offset++] = 0x00;  /* Load address low */
    kss_data[offset++] = 0x40;  /* Load address high: 0x4000 */
    kss_data[offset++] = 0xFF;  /* Data length low */
    kss_data[offset++] = 0xFF;  /* Data length high */
    kss_data[offset++] = 0x10;  /* Init address low */
    kss_data[offset++] = 0x80;  /* Init address high: 0x8010 */
    kss_data[offset++] = 0x38;  /* Play address low */
    kss_data[offset++] = 0x00;  /* Play address high: 0x0038 */
    kss_data[offset++] = 0x00;  /* Start bank */
    kss_data[offset++] = 0x00;  /* Extra header size */
    kss_data[offset++] = 0x00;  /* Reserved */
    kss_data[offset++] = kss_value;  /* Device flags */

    /* Copy MUS data (skip first 7 bytes, copy up to 0x4000 bytes) */
    mus_copy_size = mus_size - 7;
    if (mus_copy_size > MUS_DATA_SIZE) {
        mus_copy_size = MUS_DATA_SIZE;
    }
    memcpy(kss_data + offset, mus_data + 7, mus_copy_size);
    if (mus_copy_size < MUS_DATA_SIZE) {
        memset(kss_data + offset + mus_copy_size, 0, MUS_DATA_SIZE - mus_copy_size);
    }
    offset += MUS_DATA_SIZE;

    /* Copy and patch FST2.BIN */
    memcpy(fst2_patched, FST2_BIN, FST2_BIN_SIZE);

    /* Apply patches */
    fst2_patched[0x0C] = chip_value;
    fst2_patched[0xA3] = 0x7F;

    {
        static const uint8_t patch_10[] = {
            0x21, 0x00, 0x80, 0x11, 0x00, 0xD0, 0x01, 0x96,
            0x08, 0xED, 0xB0, 0x21, 0x47, 0xD0, 0x11, 0x20
        };
        memcpy(fst2_patched + 0x10, patch_10, sizeof(patch_10));
    }
    {
        static const uint8_t patch_20[] = {
            0x00, 0x01, 0x06, 0x00, 0xED, 0xB0, 0x3E, 0xC3,
            0x21, 0x9A, 0xFD, 0x32, 0x38, 0x00, 0x22, 0x39
        };
        memcpy(fst2_patched + 0x20, patch_20, sizeof(patch_20));
    }
    {
        static const uint8_t patch_30[] = {
            0x00, 0x3E, 0x40, 0x32, 0xA9, 0xD0, 0x32, 0xC8,
            0xD0, 0x3E, 0x7F, 0x32, 0xAC, 0xD0, 0x32, 0xE8,
            0xD0, 0xCD, 0xA1, 0xD0, 0xC3, 0x06, 0xD0, 0x7C,
            0x92, 0xC0, 0x7D, 0x93, 0xC9
        };
        memcpy(fst2_patched + 0x30, patch_30, sizeof(patch_30));
    }

    memcpy(kss_data + offset, fst2_patched, FST2_BIN_SIZE);
    offset += FST2_BIN_SIZE;

    *kss_size = offset;
    return 0;
}

/*
 * Convert a MUS file to KSS format with drumkit (SM1/SM2 files)
 * Structure: Header + SM1 + SM2 + MUS + FST2_patched
 */
static int mus2kss_convert_with_drumkit(
    const uint8_t *mus_data, size_t mus_size,
    const uint8_t *sm1_data, size_t sm1_size,
    const uint8_t *sm2_data, size_t sm2_size,
    uint8_t *kss_data, size_t *kss_size)
{
    size_t offset = 0;
    size_t copy_size;
    uint8_t fst2_patched[FST2_BIN_SIZE];

    /* Build KSS header for drumkit mode (16 bytes) */
    kss_data[offset++] = 'K';
    kss_data[offset++] = 'S';
    kss_data[offset++] = 'C';
    kss_data[offset++] = 'C';
    kss_data[offset++] = 0x00;  /* Load address low */
    kss_data[offset++] = 0x00;  /* Load address high: 0x0000 */
    kss_data[offset++] = 0xFF;  /* Data length low */
    kss_data[offset++] = 0xFF;  /* Data length high */
    kss_data[offset++] = 0x10;  /* Init address low */
    kss_data[offset++] = 0xC0;  /* Init address high: 0xC010 */
    kss_data[offset++] = 0x38;  /* Play address low */
    kss_data[offset++] = 0x00;  /* Play address high: 0x0038 */
    kss_data[offset++] = 0x00;  /* Start bank */
    kss_data[offset++] = 0x00;  /* Extra header size */
    kss_data[offset++] = 0x00;  /* Reserved */
    kss_data[offset++] = 0x08;  /* Device flags: MSX Audio */

    /* Copy SM1 data (skip first 7 bytes, copy up to 0x4000 bytes) */
    copy_size = sm1_size > 7 ? sm1_size - 7 : 0;
    if (copy_size > MUS_DATA_SIZE) copy_size = MUS_DATA_SIZE;
    if (copy_size > 0) {
        memcpy(kss_data + offset, sm1_data + 7, copy_size);
    }
    if (copy_size < MUS_DATA_SIZE) {
        memset(kss_data + offset + copy_size, 0, MUS_DATA_SIZE - copy_size);
    }
    offset += MUS_DATA_SIZE;

    /* Copy SM2 data (skip first 7 bytes, copy up to 0x4000 bytes) */
    copy_size = sm2_size > 7 ? sm2_size - 7 : 0;
    if (copy_size > MUS_DATA_SIZE) copy_size = MUS_DATA_SIZE;
    if (copy_size > 0) {
        memcpy(kss_data + offset, sm2_data + 7, copy_size);
    }
    if (copy_size < MUS_DATA_SIZE) {
        memset(kss_data + offset + copy_size, 0, MUS_DATA_SIZE - copy_size);
    }
    offset += MUS_DATA_SIZE;

    /* Copy MUS data (skip first 7 bytes, copy up to 0x4000 bytes) */
    copy_size = mus_size > 7 ? mus_size - 7 : 0;
    if (copy_size > MUS_DATA_SIZE) copy_size = MUS_DATA_SIZE;
    if (copy_size > 0) {
        memcpy(kss_data + offset, mus_data + 7, copy_size);
    }
    if (copy_size < MUS_DATA_SIZE) {
        memset(kss_data + offset + copy_size, 0, MUS_DATA_SIZE - copy_size);
    }
    offset += MUS_DATA_SIZE;

    /* Copy and patch FST2.BIN for drumkit mode */
    memcpy(fst2_patched, FST2_BIN, FST2_BIN_SIZE);

    /* Patch at offset 0x0C: 0 (MSX Audio mode for drumkit) */
    fst2_patched[0x0C] = 0x00;

    /* Patch at offset 0x10 (24 bytes) */
    {
        static const uint8_t patch_10[] = {
            0x21, 0x00, 0xC0, 0x11, 0x00, 0xD0, 0x01, 0x96,
            0x08, 0xED, 0xB0, 0xAF, 0x32, 0x48, 0xD8, 0xCD,
            0x03, 0xD0, 0x3E, 0x40, 0x32, 0x48, 0xD8, 0xCD
        };
        memcpy(fst2_patched + 0x10, patch_10, sizeof(patch_10));
    }

    /* Patch at offset 0x28 (11 bytes) */
    {
        static const uint8_t patch_28[] = {
            0x03, 0xD0, 0x21, 0x60, 0xD0, 0x11, 0x20, 0x00,
            0x01, 0x06, 0x00
        };
        memcpy(fst2_patched + 0x28, patch_28, sizeof(patch_28));
    }

    /* Patch at offset 0x33 (24 bytes) */
    {
        static const uint8_t patch_33[] = {
            0xED, 0xB0, 0x3E, 0xC3, 0x21, 0x9A, 0xFD, 0x32,
            0x38, 0x00, 0x22, 0x39, 0x00, 0x21, 0x00, 0x80,
            0x11, 0x00, 0x40, 0xD5, 0xC1, 0xED, 0xB0, 0x3E
        };
        memcpy(fst2_patched + 0x33, patch_33, sizeof(patch_33));
    }

    /* Patch at offset 0x4B (27 bytes) */
    {
        static const uint8_t patch_4B[] = {
            0x40, 0x32, 0xA9, 0xD0, 0x32, 0xC8, 0xD0, 0x3E,
            0x7F, 0x32, 0xAC, 0xD0, 0x32, 0xE8, 0xD0, 0xCD,
            0xA1, 0xD0, 0xC3, 0x06, 0xD0, 0x7C, 0x92, 0xC0,
            0x7D, 0x93, 0xC9
        };
        memcpy(fst2_patched + 0x4B, patch_4B, sizeof(patch_4B));
    }

    memcpy(kss_data + offset, fst2_patched, FST2_BIN_SIZE);
    offset += FST2_BIN_SIZE;

    *kss_size = offset;
    return 0;
}

/*
 * Public API: Convert a MUS file to KSS format in memory
 */
int mus2kss_convert(const uint8_t *mus_data, size_t mus_size,
                    uint8_t *kss_data, size_t *kss_size,
                    mus2kss_mode_t mode)
{
    if (!mus_data || mus_size < 8 || !kss_data || !kss_size) {
        return -1;
    }
    return mus2kss_convert_simple(mus_data, mus_size, kss_data, kss_size, mode);
}

/*
 * Public API: Convert a MUS file with drumkit to KSS format
 */
int mus2kss_convert_with_drums(
    const uint8_t *mus_data, size_t mus_size,
    const uint8_t *sm1_data, size_t sm1_size,
    const uint8_t *sm2_data, size_t sm2_size,
    uint8_t *kss_data, size_t *kss_size)
{
    if (!mus_data || mus_size < 8 || !kss_data || !kss_size) {
        return -1;
    }
    if (!sm1_data || sm1_size < 8 || !sm2_data || sm2_size < 8) {
        return -1;
    }
    return mus2kss_convert_with_drumkit(mus_data, mus_size,
                                         sm1_data, sm1_size,
                                         sm2_data, sm2_size,
                                         kss_data, kss_size);
}

/*
 * Get the required output buffer size for KSS conversion (without drumkit)
 */
size_t mus2kss_get_output_size(void)
{
    return KSS_HEADER_SIZE + MUS_DATA_SIZE + FST2_BIN_SIZE;
}

/*
 * Get the required output buffer size for KSS conversion (with drumkit)
 */
size_t mus2kss_get_output_size_with_drums(void)
{
    return KSS_HEADER_SIZE + (MUS_DATA_SIZE * 3) + FST2_BIN_SIZE;
}

/*
 * Check if a file appears to be a MUS file
 */
int mus2kss_is_mus_file(const uint8_t *data, size_t size)
{
    if (size < 8) return 0;
    return (data[0] == 0xFE);
}

/*
 * Extract drumkit base name from MUS file
 * The drumkit name is stored at offset (file_size - 124), 8 bytes
 * Returns the length of the name (0 if no drumkit or empty name)
 */
int mus2kss_get_drumkit_name(const uint8_t *data, size_t size,
                              char *name_out, size_t name_out_size)
{
    size_t offset;
    int i, len;

    if (!data || size < 135 || !name_out || name_out_size < 1) {
        if (name_out && name_out_size > 0) name_out[0] = '\0';
        return 0;
    }

    /* Drumkit name is at offset (file_size - 124), 8 bytes */
    offset = size - 124;

    /* Copy up to 8 characters, trim trailing spaces/nulls */
    len = 0;
    for (i = 0; i < 8 && i < (int)(name_out_size - 1); i++) {
        char c = (char)data[offset + i];
        if (c == '\0') break;
        name_out[i] = c;
        /* Track last non-space character */
        if (c != ' ') len = i + 1;
    }
    name_out[len] = '\0';

    /* Return 0 if name is empty or all spaces */
    return len;
}

/*
 * Read a file into memory
 */
static uint8_t *read_file(const char *path, size_t *size)
{
    FILE *fp;
    uint8_t *data;
    size_t file_size;

    fp = fopen(path, "rb");
    if (!fp) return NULL;

    fseek(fp, 0, SEEK_END);
    file_size = ftell(fp);
    fseek(fp, 0, SEEK_SET);

    data = (uint8_t *)malloc(file_size);
    if (!data) {
        fclose(fp);
        return NULL;
    }

    if (fread(data, 1, file_size, fp) != file_size) {
        free(data);
        fclose(fp);
        return NULL;
    }

    fclose(fp);
    *size = file_size;
    return data;
}

/*
 * File-based conversion function
 */
int mus2kss_convert_file(const char *input_path, const char *output_path,
                         mus2kss_mode_t mode)
{
    FILE *fp;
    uint8_t *mus_data = NULL;
    uint8_t *kss_data = NULL;
    size_t mus_size, kss_size;
    int result = -1;

    mus_data = read_file(input_path, &mus_size);
    if (!mus_data) {
        fprintf(stderr, "Error: Cannot open input file '%s'\n", input_path);
        return -1;
    }

    if (!mus2kss_is_mus_file(mus_data, mus_size)) {
        fprintf(stderr, "Error: Input does not appear to be a MUS file\n");
        goto cleanup;
    }

    kss_data = (uint8_t *)malloc(mus2kss_get_output_size());
    if (!kss_data) {
        fprintf(stderr, "Error: Out of memory\n");
        goto cleanup;
    }

    if (mus2kss_convert(mus_data, mus_size, kss_data, &kss_size, mode) != 0) {
        fprintf(stderr, "Error: Conversion failed\n");
        goto cleanup;
    }

    fp = fopen(output_path, "wb");
    if (!fp) {
        fprintf(stderr, "Error: Cannot create output file '%s'\n", output_path);
        goto cleanup;
    }

    if (fwrite(kss_data, 1, kss_size, fp) != kss_size) {
        fprintf(stderr, "Error: Failed to write output file\n");
        fclose(fp);
        goto cleanup;
    }
    fclose(fp);

    result = 0;
    printf("Converted: %s -> %s (%zu bytes)\n", input_path, output_path, kss_size);

cleanup:
    free(mus_data);
    free(kss_data);
    return result;
}

/*
 * File-based conversion function with drumkit
 */
int mus2kss_convert_file_with_drums(const char *mus_path, const char *sm1_path,
                                     const char *output_path)
{
    FILE *fp;
    uint8_t *mus_data = NULL, *sm1_data = NULL, *sm2_data = NULL;
    uint8_t *kss_data = NULL;
    size_t mus_size, sm1_size, sm2_size, kss_size;
    char sm2_path[1024];
    int result = -1;

    /* Build SM2 path from SM1 path (replace last char '1' with '2') */
    strncpy(sm2_path, sm1_path, sizeof(sm2_path) - 1);
    sm2_path[sizeof(sm2_path) - 1] = '\0';
    size_t len = strlen(sm2_path);
    if (len > 0 && sm2_path[len - 1] == '1') {
        sm2_path[len - 1] = '2';
    } else {
        /* Try replacing .SM1 with .SM2 */
        char *ext = strrchr(sm2_path, '.');
        if (ext && strcasecmp(ext, ".SM1") == 0) {
            ext[3] = '2';
        }
    }

    mus_data = read_file(mus_path, &mus_size);
    if (!mus_data) {
        fprintf(stderr, "Error: Cannot open MUS file '%s'\n", mus_path);
        return -1;
    }

    sm1_data = read_file(sm1_path, &sm1_size);
    if (!sm1_data) {
        fprintf(stderr, "Error: Cannot open SM1 file '%s'\n", sm1_path);
        goto cleanup;
    }

    sm2_data = read_file(sm2_path, &sm2_size);
    if (!sm2_data) {
        fprintf(stderr, "Error: Cannot open SM2 file '%s'\n", sm2_path);
        goto cleanup;
    }

    kss_data = (uint8_t *)malloc(mus2kss_get_output_size_with_drums());
    if (!kss_data) {
        fprintf(stderr, "Error: Out of memory\n");
        goto cleanup;
    }

    if (mus2kss_convert_with_drums(mus_data, mus_size,
                                    sm1_data, sm1_size,
                                    sm2_data, sm2_size,
                                    kss_data, &kss_size) != 0) {
        fprintf(stderr, "Error: Conversion failed\n");
        goto cleanup;
    }

    fp = fopen(output_path, "wb");
    if (!fp) {
        fprintf(stderr, "Error: Cannot create output file '%s'\n", output_path);
        goto cleanup;
    }

    if (fwrite(kss_data, 1, kss_size, fp) != kss_size) {
        fprintf(stderr, "Error: Failed to write output file\n");
        fclose(fp);
        goto cleanup;
    }
    fclose(fp);

    result = 0;
    printf("Converted with drumkit: %s + %s + %s -> %s (%zu bytes)\n",
           mus_path, sm1_path, sm2_path, output_path, kss_size);

cleanup:
    free(mus_data);
    free(sm1_data);
    free(sm2_data);
    free(kss_data);
    return result;
}

/*
 * Auto-convert MUS file with automatic drumkit detection
 * Looks for SM1/SM2 files in the same directory as the MUS file
 */
int mus2kss_convert_file_auto(const char *mus_path, const char *output_path)
{
    uint8_t *mus_data = NULL;
    size_t mus_size;
    char drumkit_name[16];
    char sm1_path[1024];
    char *dir_end;
    int has_drums = 0;

    /* Read MUS file */
    mus_data = read_file(mus_path, &mus_size);
    if (!mus_data) {
        fprintf(stderr, "Error: Cannot open MUS file '%s'\n", mus_path);
        return -1;
    }

    /* Extract drumkit name from MUS */
    if (mus2kss_get_drumkit_name(mus_data, mus_size, drumkit_name, sizeof(drumkit_name)) > 0) {
        /* Build SM1 path in same directory as MUS file */
        strncpy(sm1_path, mus_path, sizeof(sm1_path) - 1);
        sm1_path[sizeof(sm1_path) - 1] = '\0';

        /* Find last path separator */
        dir_end = strrchr(sm1_path, '/');
        if (!dir_end) dir_end = strrchr(sm1_path, '\\');

        if (dir_end) {
            /* Append drumkit.SM1 to directory */
            snprintf(dir_end + 1, sizeof(sm1_path) - (dir_end - sm1_path) - 1,
                     "%s.SM1", drumkit_name);
        } else {
            /* No directory, just use drumkit.SM1 */
            snprintf(sm1_path, sizeof(sm1_path), "%s.SM1", drumkit_name);
        }

        /* Check if SM1 file exists */
        FILE *fp = fopen(sm1_path, "rb");
        if (fp) {
            fclose(fp);
            has_drums = 1;
        }
    }

    free(mus_data);

    if (has_drums) {
        return mus2kss_convert_file_with_drums(mus_path, sm1_path, output_path);
    } else {
        return mus2kss_convert_file(mus_path, output_path, MUS2KSS_MODE_MSXAUDIO);
    }
}

/* Print usage */
static void print_usage(const char *prog)
{
    fprintf(stderr, "FST Sound Tracker MUS to KSS converter\n");
    fprintf(stderr, "Original by NYYRIKKI, C port for modizer\n\n");
    fprintf(stderr, "Usage: %s [options] input.mus output.kss [drumkit.sm1]\n", prog);
    fprintf(stderr, "Options:\n");
    fprintf(stderr, "  -f    : FMPAC chip mode (without drumkit)\n");
    fprintf(stderr, "  -a    : MSX Audio chip mode (without drumkit, default)\n");
    fprintf(stderr, "  -auto : Auto-detect drumkit from MUS metadata\n");
    fprintf(stderr, "\nWith explicit drumkit:\n");
    fprintf(stderr, "  %s input.mus output.kss drumkit.sm1\n", prog);
    fprintf(stderr, "  (SM2 file is auto-detected from SM1 path)\n");
}

#ifndef MUS2KSS_LIBRARY
/* Command-line interface */
int main(int argc, char *argv[])
{
    mus2kss_mode_t mode = MUS2KSS_MODE_MSXAUDIO;
    const char *input_path = NULL;
    const char *output_path = NULL;
    const char *drumkit_path = NULL;
    int auto_detect = 0;
    int i;

    for (i = 1; i < argc; i++) {
        if (strcmp(argv[i], "-f") == 0) {
            mode = MUS2KSS_MODE_FMPAC;
        } else if (strcmp(argv[i], "-a") == 0) {
            mode = MUS2KSS_MODE_MSXAUDIO;
        } else if (strcmp(argv[i], "-auto") == 0) {
            auto_detect = 1;
        } else if (strcmp(argv[i], "-h") == 0 || strcmp(argv[i], "--help") == 0) {
            print_usage(argv[0]);
            return 0;
        } else if (!input_path) {
            input_path = argv[i];
        } else if (!output_path) {
            output_path = argv[i];
        } else if (!drumkit_path) {
            drumkit_path = argv[i];
        }
    }

    if (!input_path || !output_path) {
        print_usage(argv[0]);
        return 1;
    }

    if (drumkit_path) {
        return mus2kss_convert_file_with_drums(input_path, drumkit_path, output_path);
    } else if (auto_detect) {
        return mus2kss_convert_file_auto(input_path, output_path);
    } else {
        return mus2kss_convert_file(input_path, output_path, mode);
    }
}
#endif /* MUS2KSS_LIBRARY */
